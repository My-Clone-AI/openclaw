export type DocsKey = keyof typeof en;
export type KT = (key: DocsKey) => string;

const lang = (locale: string) => locale.toLowerCase().split("-")[0] ?? "en";

export function docsTranslator(locale: string): KT {
  const catalog = ({ en, pt, es } as Record<string, Record<DocsKey, string>>)[lang(locale)] ?? en;
  return (key) => catalog[key];
}
