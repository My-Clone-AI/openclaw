const CATALOGS: Record<string, Record<DocsKey, string>> = { en, pt, es };

export function docsTranslator(locale: string): DCT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key];
}

/** A word for an NSVX value when this catalog knows it; otherwise NSVX's own text. */
export function docsWord(dt: DCT, key: string, fallback: string): string {
  return Object.hasOwn(en, key) ? dt(key as DocsKey) : fallback;
}
