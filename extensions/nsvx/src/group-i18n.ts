const CATALOGS: Record<string, Record<GroupKey, string>> = { en, pt, es };

export function groupTranslator(locale: string): GT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key];
}
