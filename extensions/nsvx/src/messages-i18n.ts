const CATALOGS: Record<string, Record<MessagesKey, string>> = { en, pt, es };

export function messagesTranslator(locale: string): MT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key];
}
