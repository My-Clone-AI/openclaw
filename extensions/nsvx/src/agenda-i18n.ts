const CATALOGS: Record<string, Record<AgendaKey, string>> = { en, pt, es };

export function agendaTranslator(locale: string): AT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key];
}
