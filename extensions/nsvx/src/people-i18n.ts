const CATALOGS: Record<string, Record<PeopleKey, string>> = { en, pt, es };

export type PT = (key: PeopleKey) => string;

export function peopleTranslator(locale: string): PT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key];
}

/** Group history keys NSVX writes (social_groups events). */
export function eventKey(action: string): PeopleKey | undefined {
  const key = `ev_${action}`;
  return Object.hasOwn(en, key) ? (key as PeopleKey) : undefined;
}
