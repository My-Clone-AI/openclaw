const CATALOGS: Record<string, Record<AiKey, string>> = { en, pt, es };

export type AiT = (key: string) => string;

/** Unknown keys (a lane or state NSVX adds later) show as NSVX sent them. */
export function aiTranslator(locale: string): AiT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => (Object.hasOwn(catalog, key) ? catalog[key as AiKey] : key);
}
