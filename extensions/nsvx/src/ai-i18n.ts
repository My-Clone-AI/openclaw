const CATALOGS: Record<string, Record<AiKey, string>> = { en, pt, es };

export type AT = (key: AiKey) => string;

export function aiTranslator(locale: string): AT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key];
}

/** The catalog key for a dynamic NSVX code (`w_five_hour`, `t_prepared`), when one exists. */
export function aiKey(prefix: string, code: string | null | undefined): AiKey | undefined {
  const key = `${prefix}${code ?? ""}`;
  return Object.hasOwn(en, key) ? (key as AiKey) : undefined;
}
