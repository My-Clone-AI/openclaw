/** Keys are plain strings because many arrive from NSVX; an unknown one shows as it is. */
export type LT = (key: string) => string;

export const LEGAL_KEYS = Object.keys(WORDS);

export function legalTranslator(locale: string): LT {
  const code = locale.toLowerCase().split("-")[0];
  const at = code === "pt" ? 1 : code === "es" ? 2 : 0;
  return (key) => (WORDS as Record<string, readonly string[]>)[key]?.[at] ?? key;
}
