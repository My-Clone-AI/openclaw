const CATALOGS: Record<string, Record<AccessKey, string>> = { en, pt, es };

export function accessTranslator(locale: string): AT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key];
}
