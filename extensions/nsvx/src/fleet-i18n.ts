const CATALOGS: Record<string, Record<FleetKey, string>> = { en, pt, es };

export type FT = (key: FleetKey) => string;

export function fleetTranslator(locale: string): FT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key];
}

/** A label for an NSVX state code, or the code itself when this build has no word for it. */
export function stateLabel(ft: FT, prefix: "status_" | "st_", code: string | null | undefined) {
  if (!code) {
    return "—";
  }
  const key = `${prefix}${code}`;
  return Object.hasOwn(en, key) ? ft(key as FleetKey) : code.replaceAll("_", " ");
}

