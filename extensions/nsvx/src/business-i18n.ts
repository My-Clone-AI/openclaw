const CATALOGS: Record<string, Record<BusinessKey, string>> = { en, pt, es };

/** Unknown states NSVX may add show as their own word ("run_new" shows "new"), never as a blank. */
export function businessTranslator(locale: string): BT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key] ?? key.replace(/^[a-z]+_/, "").replaceAll("_", " ");
}
