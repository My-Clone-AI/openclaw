const CATALOGS: Record<string, Record<DeviceKey, string>> = { en, pt, es };

export function deviceTranslator(locale: string): DT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key];
}

/** NSVX names for readiness checks and warnings, shown in words when known. */
export function deviceWord(dt: DT, name: string): string {
  return Object.hasOwn(en, name) ? dt(name as DeviceKey) : name;
}
