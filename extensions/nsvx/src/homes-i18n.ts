const CATALOGS: Record<string, Record<HK, string>> = { en, pt, es };

export type HT = (key: HK) => string;

export function homesTranslator(locale: string): HT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key];
}

