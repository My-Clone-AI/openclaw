const CATALOGS: Record<string, Record<GrowKey, string>> = { en, pt, es };

export function growTranslator(locale: string): GT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key];
}

/** A word for a value NSVX may extend (states, pipeline steps); unknown values show as they are. */
export function growWord(gt: GT, value: string): string {
  return Object.hasOwn(en, value) ? gt(value as GrowKey) : value;
}
