const CATALOGS: Record<string, Record<AviationKey, string>> = { en, pt, es };

export function aviationTranslator(locale: string): AT {
  const catalog = CATALOGS[locale.toLowerCase().split("-")[0] ?? "en"] ?? en;
  return (key) => catalog[key];
}

/** A word for an NSVX value when this catalog knows it; otherwise NSVX's own text. */
export function aviationWord(at: AT, key: string, fallback: string): string {
  return Object.hasOwn(en, key) ? at(key as AviationKey) : fallback;
}
